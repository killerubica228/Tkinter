# Задание 1. Исправление синтаксических ошибок
#
# Найденные ошибки:
#   1) после условия if не было двоеточия;
#   2) после else не было двоеточия;
#   3) между строкой и переменной в print() не было запятой (или знака +);
#   4) код был записан в одну строку, а Python требует отступов в блоках if/else.

name = input("Введите имя: ").strip()
if name != "":
    print("Здравствуйте,", name)
else:
    print("Имя не введено")
