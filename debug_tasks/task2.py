# Задание 2. Поиск логической ошибки
#
# Ошибка: условия были перепутаны. Для number < 0 выводилось
# «Положительное число», а для number > 0 — «Отрицательное число».
# Исправление: поменять сообщения местами.
#
# Проверка: 10 -> положительное, -5 -> отрицательное, 0 -> равно нулю.

try:
    number = int(input("Введите число: "))
except ValueError:
    print("Ошибка: нужно ввести целое число.")
else:
    if number > 0:
        print("Положительное число")
    elif number < 0:
        print("Отрицательное число")
    else:
        print("Число равно нулю")
