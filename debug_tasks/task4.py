# Задание 4. Проверка правильности вычислений
#
# Ошибка: приоритет операций. В выражении  a + b + c / 3  сначала
# делится только c, а потом складывается:  10 + 20 + 30/3 = 40, а не 20.
# Исправление: сумму нужно взять в скобки:  (a + b + c) / 3.

a = 10
b = 20
c = 30
average = (a + b + c) / 3
print("Среднее значение:", average)          # 20.0

# Проверка на других значениях: (a, b, c, ожидаемое среднее)
tests = [(1, 2, 3, 2), (5, 5, 5, 5), (0, 0, 0, 0), (-3, 3, 6, 2), (2.5, 3.5, 6, 4)]
print("\nПроверка на других значениях:")
for x, y, z, expected in tests:
    result = (x + y + z) / 3
    status = "OK" if abs(result - expected) < 1e-9 else "ОШИБКА"
    print(f"  ({x} + {y} + {z}) / 3 = {result:.4g}, ожидалось {expected} -> {status}")
